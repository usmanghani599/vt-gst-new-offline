#!/usr/bin/env node
/**
 * Writes electron/build-config.ts from environment variables at build time.
 *
 *   VTGST_SERVER_URL            online VTGST server (licensing + sync), e.g. https://app.example.com
 *   VTGST_GOOGLE_CLIENT_ID      Google OAuth "Desktop app" client id (Drive backup)
 *   VTGST_GOOGLE_CLIENT_SECRET  Google OAuth desktop client secret
 *   VTGST_LICENSE_PUBLIC_KEY    Ed25519 public key PEM (or base64 of it) from scripts/generate-desktop-keys.ts
 *
 * Instead of environment variables you can put the values in `build.env` (see
 * build.env.example) and the public key in `license-public.pem`, both in the
 * project root and never committed. Real environment variables win.
 *
 * `--release` refuses to continue when production values are missing.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const release = process.argv.includes('--release');

// Optional build.env file: KEY=value lines, # comments, optional quotes.
const fileEnv = {};
const envFile = path.join(ROOT, 'build.env');
if (fs.existsSync(envFile)) {
  for (const line of fs.readFileSync(envFile, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && !line.trim().startsWith('#')) fileEnv[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2');
  }
}
const env = { ...fileEnv, ...Object.fromEntries(Object.entries(process.env).filter(([, v]) => v)) };

let pub = (env.VTGST_LICENSE_PUBLIC_KEY || '').trim();
const pemFile = path.resolve(ROOT, env.VTGST_LICENSE_PUBLIC_KEY_FILE || 'license-public.pem');
if (!pub && fs.existsSync(pemFile)) pub = fs.readFileSync(pemFile, 'utf8').trim();
if (pub && !pub.includes('BEGIN')) pub = Buffer.from(pub, 'base64').toString('utf8');

const manifestHashFile = path.join(ROOT, 'build', 'server-manifest.sha256');
const serverManifestHash = fs.existsSync(manifestHashFile) ? fs.readFileSync(manifestHashFile, 'utf8').trim() : '';
const packFile = path.join(ROOT, 'build', 'server.asar');
let serverPackHash = '';
if (fs.existsSync(packFile)) {
  const { createHash } = await import('crypto');
  serverPackHash = createHash('sha256').update(fs.readFileSync(packFile)).digest('hex');
  fs.writeFileSync(path.join(ROOT, 'build', 'server-pack.sha256'), serverPackHash);
}

let commit = 'unknown';
try {
  commit = (await import('child_process')).execSync('git rev-parse --short HEAD', { cwd: ROOT }).toString().trim();
} catch {
  /* not a git checkout */
}
const buildId = `${commit}-${new Date().toISOString().slice(0, 16).replace(/[-:T]/g, '')}`;

const cfg = {
  buildId,
  serverManifestHash,
  serverPackHash,
  serverUrl: (env.VTGST_SERVER_URL || 'http://localhost:3000').replace(/\/+$/, ''),
  googleClientId: env.VTGST_GOOGLE_CLIENT_ID || '',
  googleClientSecret: env.VTGST_GOOGLE_CLIENT_SECRET || '',
  licensePublicKey: pub,
};

if (release) {
  const missing = [];
  if (!env.VTGST_SERVER_URL || !cfg.serverUrl.startsWith('https://')) missing.push('VTGST_SERVER_URL (https)');
  if (!cfg.licensePublicKey) missing.push('VTGST_LICENSE_PUBLIC_KEY');
  if (!serverManifestHash || !serverPackHash) missing.push('build/server.asar (run npm run bundle first)');
  if (missing.length) {
    console.error(`Release build is missing: ${missing.join(', ')}`);
    console.error('Set them in build.env + license-public.pem in the project root (see build.env.example), or as environment variables.');
    process.exit(1);
  }
  if (!cfg.googleClientId) console.warn('! VTGST_GOOGLE_CLIENT_ID not set: Google Drive backup will be disabled in this build.');
}

const out = `// AUTO-GENERATED by scripts/write-build-config.mjs — do not edit or commit secrets.
export const BUILD_CONFIG = ${JSON.stringify(cfg, null, 2)} as const;
`;
fs.writeFileSync(path.join(ROOT, 'electron', 'build-config.ts'), out);
console.log(`Build ${buildId} config written (server: ${cfg.serverUrl}, google: ${cfg.googleClientId ? 'yes' : 'no'}, public key: ${cfg.licensePublicKey ? 'yes' : 'NO'})`);
