#!/usr/bin/env node
/**
 * Builds the desktop (SQLite) Prisma schema from the online (MySQL) schema and
 * produces an incremental SQL migration when the data model changed.
 *
 *   npm run schema
 *
 * prisma/upstream.schema.prisma  (copied from the online app by sync-upstream)
 *   -> prisma/schema.prisma      (SQLite + driverAdapters, server-only models removed)
 *   -> migrations/NNNN_<name>.sql (only when something changed)
 *   -> migrations/schema.snapshot.prisma (state after the last migration)
 *
 * Migrations are applied at app start by electron/db/migrator.ts inside the
 * encrypted database, so customer data is upgraded in place.
 */
import fs from 'fs';
import path from 'path';
import { execFileSync } from 'child_process';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const UPSTREAM = path.join(ROOT, 'prisma', 'upstream.schema.prisma');
const OUT = path.join(ROOT, 'prisma', 'schema.prisma');
const MIG_DIR = path.join(ROOT, 'migrations');
const SNAPSHOT = path.join(MIG_DIR, 'schema.snapshot.prisma');

/** Models that only exist on the online server. */
const SERVER_ONLY_MODELS = ['DesktopLicense', 'DesktopActivation', 'DesktopEvent', 'DesktopSyncLog'];

let s = fs.readFileSync(UPSTREAM, 'utf8');

for (const m of SERVER_ONLY_MODELS) {
  // Remove the model block, including any `///` doc comment lines right above it.
  s = s.replace(new RegExp(`(?:^///.*\\n)*^model ${m} \\{[\\s\\S]*?^\\}\\n?`, 'm'), '');
}

s = s
  .replace(/provider\s*=\s*"mysql"/, 'provider = "sqlite"')
  .replace(/\s@db\.\w+(\([^)]*\))?/g, '')
  .replace(
    /generator client \{[^}]*\}/,
    'generator client {\n  provider        = "prisma-client-js"\n  binaryTargets   = ["native", "windows", "darwin", "darwin-arm64", "debian-openssl-3.0.x"]\n}'
  );

const header =
  '// AUTO-GENERATED by scripts/make-sqlite-schema.mjs from prisma/upstream.schema.prisma.\n' +
  '// Do not edit by hand. Run `npm run schema` after syncing upstream.\n\n';
fs.writeFileSync(OUT, header + s);
console.log('Wrote prisma/schema.prisma');

fs.mkdirSync(MIG_DIR, { recursive: true });
const prismaBin = path.join(ROOT, 'node_modules', '.bin', process.platform === 'win32' ? 'prisma.cmd' : 'prisma');
const from = fs.existsSync(SNAPSHOT) ? ['--from-schema-datamodel', SNAPSHOT] : ['--from-empty'];
const sql = execFileSync(prismaBin, ['migrate', 'diff', ...from, '--to-schema-datamodel', OUT, '--script'], {
  cwd: ROOT,
  encoding: 'utf8',
});

if (!sql.trim() || /This is an empty migration/.test(sql)) {
  console.log('Data model unchanged — no new migration.');
} else {
  const existing = fs.readdirSync(MIG_DIR).filter((f) => /^\d{4}_.*\.sql$/.test(f));
  const next = String(existing.length + 1).padStart(4, '0');
  const name = process.argv[2] || (existing.length ? 'upstream_update' : 'init');
  const file = path.join(MIG_DIR, `${next}_${name}.sql`);
  fs.writeFileSync(file, sql);
  fs.copyFileSync(OUT, SNAPSHOT);
  console.log(`Wrote ${path.relative(ROOT, file)}`);
}
